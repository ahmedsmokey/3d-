/**
 * Format any numerical price in Iraqi Dinars (د.ع / IQD)
 */
export function formatPrice(amount, lang = 'ar') {
  if (amount == null || isNaN(amount)) return lang === 'ar' ? '0 د.ع' : '0 IQD';
  const val = Math.round(Number(amount));
  const numStr = val.toLocaleString('en-US');
  return lang === 'ar' ? `${numStr} د.ع` : `${numStr} IQD`;
}
